import assert from 'node:assert/strict';
import { evaluateWalkForward, candidateGrid } from '../research/store-optimization.mjs';
const days=Array.from({length:75},(_,i)=>({shop:'A',date:new Date(Date.UTC(2025,0,i+1)).toISOString().slice(0,10),machines:[{tableNo:'1',p4:.8},{tableNo:'2',p4:.2}]}));
const seen=[];
const predictor=({history,targetDate,candidate})=>{assert(history.every(d=>d.date<targetDate));assert(Object.isFrozen(history));seen.push({targetDate,candidate});return ['1','2'];};
const opts={days,shop:'A',predictor,candidates:[{id:'baseline',windowDays:180},{id:'short',windowDays:30}],outerDates:days.slice(-3).map(d=>d.date),minHistoryDays:20,innerDays:5,k:1};
const result=await evaluateWalkForward(opts);
assert.equal(result.folds.length,3);assert.equal(result.decision,'RESEARCH_ONLY');
assert.equal(result.folds[0].selected,'baseline');assert.equal(result.folds[0].delta,0);
assert(result.folds.every(f=>f.selectionDates.every(d=>d<f.targetDate)));
const cutoff=opts.outerDates[0];
const poisoned=days.map(d=>d.date>=cutoff?{...d,machines:[{tableNo:'1',p4:0},{tableNo:'2',p4:1}]}:d);
const changed=await evaluateWalkForward({...opts,days:poisoned,outerDates:[cutoff]});
assert.deepEqual(changed.folds[0].selection,result.folds[0].selection);
assert.equal(changed.folds[0].selected,result.folds[0].selected);
assert.notEqual(changed.folds[0].baseline,result.folds[0].baseline);
assert.deepEqual(changed.folds[0].predictionHashes,result.folds[0].predictionHashes);
await assert.rejects(()=>evaluateWalkForward({...opts,days:[...days,days[0]]}),/duplicate/);
await assert.rejects(()=>evaluateWalkForward({...opts,predictor:()=>['1','1']}),/duplicate/);
await assert.rejects(()=>evaluateWalkForward({...opts,days:days.map((d,i)=>i===0?{...d,availableDate:cutoff}:d)}),/availableDate/);
assert.equal(candidateGrid().length,8);
console.log('PASS research chronology, immutable input, future/target poisoning, baseline tie, receipt hashes, invalid data guards');
const adaptive=await evaluateWalkForward({...opts,predictor:({candidate})=>candidate.id==='baseline'?['2','1']:['1','2']});
assert(adaptive.folds.every(f=>f.selected==='short'&&Math.abs(f.delta-.6)<1e-10));
const missing=await evaluateWalkForward({...opts,minHistoryDays:100});
assert.equal(missing.pairedDays,0);assert.equal(missing.meanDelta,null);
assert.equal(missing.decision,'RESEARCH_ONLY');
console.log('PASS paired candidate selection and no-data abstention');
